#!/usr/bin/env python3
"""Write docs/STATUS.md from the last results in lab-results/ (engine tests, GPU suite, lab scenarios)."""
import json, pathlib, re, subprocess, datetime
root = pathlib.Path(__file__).resolve().parent.parent
res = root / "lab-results"
def git(*a):
    try: return subprocess.run(["git", *a], cwd=root, capture_output=True, text=True).stdout.strip()
    except Exception: return "?"
def age(path):
    if not path.exists(): return None
    return datetime.datetime.fromtimestamp(path.stat().st_mtime, datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
L = ["# Status", "", "Generated by `tools/status.py` from the last runs of `tools/check.sh` (see CLAUDE.md for the rules).", "",
     f"Commit at generation: `{git('rev-parse', '--short', 'HEAD')}` ({git('log', '-1', '--format=%cd', '--date=short')}){' with uncommitted changes' if git('status', '--porcelain') else ''}.", ""]
# engine
e = res / "engine.txt"
L += ["## Engine tests (`cargo test --release` at the root: sf-engine and sf-demo)", ""]
if e.exists():
    t = e.read_text()
    m = re.findall(r"test result: (\w+)\. (\d+) passed; (\d+) failed; (\d+) ignored", t)
    p = sum(int(x[1]) for x in m); f = sum(int(x[2]) for x in m); ig = sum(int(x[3]) for x in m)
    L.append(f"**{'PASS' if f == 0 and m else 'FAIL'}**: {p} passed, {f} failed, {ig} ignored · run {age(e)}")
    for name in re.findall(r"test (\S+) \.\.\. FAILED", t): L.append(f"- FAILED `{name}`")
else: L.append("not run")
L.append("")
# GPU
g = res / "gpu.json"
L += ["## GPU suite (`node engine/gpu/test_gpu.cjs`, headless Chrome, software WebGPU)", ""]
if g.exists():
    d = json.loads(g.read_text()); r = d["results"]
    ok = sum(1 for v in r.values() if v.get("ok"))
    L.append(f"**{'PASS' if ok == len(r) else 'FAIL'}**: {ok} of {len(r)} · run {age(g)}{' (scenes: ' + ', '.join(d['scenes']) + ')' if d.get('scenes') else ''}")
    L += ["", "| Test | Result | Key values |", "| --- | --- | --- |"]
    for k, v in r.items():
        kv = {a: b for a, b in v.items() if a != "ok" and not isinstance(b, (list, dict))}
        L.append(f"| {k} | {'pass' if v.get('ok') else '**FAIL**'} | {', '.join(f'{a} {b:.3g}' if isinstance(b, float) else f'{a} {b}' for a, b in list(kv.items())[:4])} |")
else: L.append("not run")
L.append("")
# lab
L += ["## Lab scenarios (`node game/lab/lab.cjs`, virtual clock; see docs/LAB.md)", ""]
labs = sorted(p for p in res.glob("*.json") if p.stem not in ("gpu", "all"))
if labs:
    L += ["| Scenario | Frames | Result | Failed checks | Roof m | Settled s | GPU ms median (software) | Run |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for p in labs:
        try: d = json.loads(p.read_text())
        except Exception: continue
        if "checks" not in d: continue
        bad = [f"{c['name']} = {c['value']}" for c in d["checks"] if not c["pass"]]
        ph = d.get("physics", {}); pf = d.get("perf", {})
        frames = d.get("frames"); steps = pf.get("steps")
        L.append(f"| {d['scenario']} | {frames}{' (shortened)' if d.get('shortened') else ''} | {'pass' if d['pass'] else '**FAIL**'} | {'; '.join(bad) or '-'} | {ph.get('roof_m', ['?', '?'])[0]} → {ph.get('roof_m', ['?', '?'])[1]} | {ph.get('settled_s') or 'no'} | {pf.get('gpu_ms', {}).get('median', '?')} | {age(p)} |")
else: L.append("not run")
L += ["", "## Known open problems", "", "Kept by hand in docs/GPU.md (\"Still to do\") and docs/LAB.md (\"What it found first\"); a failing check above that is listed there is known, any other is new.", ""]
(root / "docs/STATUS.md").write_text("\n".join(L))
print("docs/STATUS.md written")
